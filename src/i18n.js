function normalizeLocale(value) {
  return value === 'zh-CN' ? 'zh-CN' : 'en-US';
}

function t(locale, key, ...args) {
  const value = messages[normalizeLocale(locale)][key];
  return typeof value === 'function' ? value(...args) : value;
}

function localizeProject(project, locale) {
  const translation = projectTranslations[project.id]?.[normalizeLocale(locale)];
  if (!translation) return project;
  return { ...project, name: translation[0], description: translation[1] };
}

